RE_DECOMP_E_ACUTE_STANDALONE = re.compile(r"(?<=\s)e´(?=\s|[.,;:])")

# Carets de nota de rodapé colados ao final de palavras (ex: Câmara^, razões^, sintese^)
RE_FOOTNOTE_CARET = re.compile(r"\b([A-Za-zÀ-ÿ]{2,})\^+(?=\s|[.,;:!?)\]]|$)")

