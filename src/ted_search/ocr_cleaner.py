# Acentuação decomposta típica de OCR antigo (ex: incompete^ncia, ac¸a~o, aco´rda~o, e´)
RE_DECOMP_CIRCUMFLEX = re.compile(r"([aAeEoO])\^([nNsSmMrR]|[a-zà-ÿ]{2,})")
RE_DECOMP_TILDE_AO = re.compile(r"([aA])~([oO]s?|[eE]s)")
RE_DECOMP_TILDE_OE = re.compile(r"([oO])~([eE]s)")
RE_DECOMP_CEDILLA = re.compile(r"([cC])[¸,]\s*([aAoOuUãõáéíóú])")
