def is_gibberish_ocr_line(line: str) -> bool:
    """Detecta linhas de puro ruído de OCR (brasão cursivo da OAB, assinaturas escaneadas ou blocos corrompidos)."""
    s = line.strip()
    if not s:
        return False
    # Padrões clássicos do brasão cursivo "Conselho Federal da Ordem dos Advogados do Brasil" e itálicos ilegíveis
    if re.search(
        r"9Ídi|yAidefa|SkccioM|v4\(fyocac|coatraMg|bivgrg|C\s*o\s*a\s*a\s*\^|doá\s+Q|O9Ídv|nrtf<|OdddiM|Ó\^íxlf|rnãmiaN|ReWtor",
        s,
    ):
        return True
    # Linhas de carimbo numérico isolado de assinatura digital (ex: "1016-4941-71")
    if re.match(r"^\d{4}-\d{4}-\d{2}$", s):
        return True
    # Linhas curtas compostas apenas por símbolos/pontuação quebrada
    weird_chars = sum(1 for c in s if c in "^■\\«»~|<>*@#$%&={}")
    slash_tokens = len(
        re.findall(
            r"(?:^|\s)[/\\][A-Za-zÀ-ÿ]|[A-Za-zÀ-ÿ][/\\][A-Za-zÀ-ÿ](?:\s|$)|\([a-z]{2}\b|;[A-Za-z]",
            s,
        )
    )
    alpha_words = re.findall(r"\b[A-Za-zÀ-ÿ]{4,}\b", s)
    if weird_chars >= 3 and (weird_chars + slash_tokens * 2) > len(alpha_words):
        return True
    if slash_tokens >= 3:
        return True
    if len(s) < 45 and (weird_chars >= 2 or re.match(r"^[(\W_0-9\-—%#\"']+$", s)):
        return True
    return False


def _match_case(original: str, replacement: str) -> str:
    if original.isupper():
        return replacement.upper()
    if original[0].isupper() and original[1:].islower():
        return replacement.capitalize()
    return replacement


def _replace_ocr_word(match: re.Match[str]) -> str:
    word = match.group(1)
    low = word.lower()
    fixed = OCR_WORD_MAP.get(low)
    if not fixed:
        return word
    return _match_case(word, fixed)


def clean_ocr_text(raw: str | None, *, multiline: bool = True) -> str:
    """Limpa entidades HTML, tags vazadas, hifenizações quebradas e erros de OCR jurídicos."""
    if not raw:
        return ""

    txt = html.unescape(raw)
    txt = txt.replace("\r\n", "\n").replace("\r", "\n")

    # 1. Remover figuras base64 e tags HTML vazadas (ex: Súmulas e Ementas formatadas)
    if "<" in txt:
        txt = RE_HTML_FIGURE_BASE64.sub(" ", txt)
        txt = RE_HTML_BREAKS.sub("\n", txt)
        txt = RE_HTML_TAGS.sub("", txt)

    # 2. Remover caracteres invisíveis/corrompidos (Hangul Filler U+3164, Black Square U+25A0, Replacement U+FFFD)
    txt = txt.replace("\u3164", " ").replace("\u00a0", " ").replace("\ufffd", "").replace("\u25a0", " ")

    # 3. Unir palavras quebradas por soft-hyphen (U+00AD) em quebras de linha de PDFs
    if "\u00ad" in txt:
        txt = re.sub(r"\u00ad\s*", "", txt)

    # 4. Recompor acentuação decomposta de OCR (e^ -> ê, a~o -> ão, c¸ -> ç, o´ -> ó)
    if "^" in txt or "~" in txt or "¸" in txt or "´" in txt:
        txt = RE_DECOMP_CIRCUMFLEX.sub(
            lambda m: {"a": "â", "A": "Â", "e": "ê", "E": "Ê", "o": "ô", "O": "Ô"}[m.group(1)] + m.group(2),
            txt,
        )
        txt = RE_DECOMP_CEDILLA.sub(
            lambda m: ("Ç" if m.group(1).isupper() else "ç") + m.group(2),
            txt,
        )
        txt = RE_DECOMP_ACUTE_IN_WORD.sub(
            lambda m: m.group(1) + {"a": "á", "e": "é", "i": "í", "o": "ó", "u": "ú"}[m.group(2)] + m.group(3),
            txt,
        )
        txt = RE_DECOMP_TILDE_AO.sub(
            lambda m: ("Ã" if m.group(1).isupper() else "ã") + m.group(2),
            txt,
        )
        txt = RE_DECOMP_TILDE_OE.sub(
            lambda m: ("Õ" if m.group(1).isupper() else "õ") + m.group(2),
            txt,
        )
        txt = RE_DECOMP_E_ACUTE_STANDALONE.sub("é", txt)
        txt = RE_FOOTNOTE_CARET.sub(r"\1", txt)

    # 5. Filtrar linhas de puro ruído de OCR (brasão cursivo, assinaturas, blocos ilegíveis)
    if "\n" in txt:
        cleaned_lines: list[str] = []
        for ln in txt.split("\n"):
            ln_clean = RE_PAGE_FOOTER_NOISE.sub(r"\1", ln)
            if is_gibberish_ocr_line(ln_clean):
                continue
            cleaned_lines.append(ln_clean)
        txt = "\n".join(cleaned_lines)

    # 6. Corrigir hifenizações quebradas (pronomes enclíticos, compostos jurídicos e palavras partidas)
    if "-" in txt:
        txt = RE_ENCLITIC_HYPHEN.sub(r"\1-\2", txt)
        txt = RE_COMPOUND_HYPHEN.sub(r"\1-\2", txt)
        for pat, repl in MIDWORD_HYPHEN_PATTERNS:
            txt = pat.sub(repl, txt)

    # 7. Aplicar dicionário de palavras jurídicas corrompidas no OCR e regras morfológicas
    txt = RE_WORD_TOKEN.sub(_replace_ocr_word, txt)
    for pat, repl in MORPH_OCR_PATTERNS:
        txt = pat.sub(repl, txt)
    txt = RE_WORD_TOKEN.sub(_replace_ocr_word, txt)

    # 8. Normalizar espaçamento em citações de artigos (ex: art.34 -> art. 34)
    txt = RE_GLUED_ART.sub(r"\1 \2", txt)

    # 9. Normalizar espaços múltiplos e quebras de linha excessivas
    txt = re.sub(r"[ \t]+", " ", txt)
    if multiline:
        txt = re.sub(r" *\n *", "\n", txt)
        txt = re.sub(r"\n{3,}", "\n\n", txt)
    else:
        txt = txt.replace("\n", " ")
        txt = re.sub(r" {2,}", " ", txt)

    return txt.strip()
